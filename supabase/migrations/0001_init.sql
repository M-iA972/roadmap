-- =============================================================================
-- Roadmap : schéma initial (0001_init)
-- =============================================================================
-- Ce fichier est la structure de départ de la base, telle qu'elle existe
-- avant les policies RLS du J7 : tables, contraintes, fonction et trigger de
-- création des profils, bucket Storage des photos.
-- La Row Level Security n'y est pas encore activée : les policies RLS seront
-- ajoutées au J7, dans de nouveaux fichiers de migration.
-- Structure uniquement : aucune donnée, aucune clé, aucun secret.
--
-- ATTENTION : la base en ligne contient déjà tout cela. Ce fichier ne doit pas
-- y être exécuté. Pour que la CLI Supabase le considère comme déjà appliqué :
--   supabase migration repair --status applied 0001
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Table modules : les grandes zones du produit (facturation, onboarding…).
-- « generated by default as identity » : l'id est un numéro attribué
-- automatiquement (1, 2, 3…), qu'on peut aussi fixer à la main si besoin.
-- Le nom d'un module est unique.
-- -----------------------------------------------------------------------------
create table public.modules (
  id          bigint generated by default as identity primary key,
  name        text not null,
  color       text not null,
  description text,
  created_at  timestamptz not null default now(),

  constraint modules_name_key unique (name)
);


-- -----------------------------------------------------------------------------
-- Table sprints : périodes de travail d'une ou deux semaines.
-- Le statut ne peut prendre que 3 valeurs (contrainte CHECK).
-- -----------------------------------------------------------------------------
create table public.sprints (
  id         bigint generated by default as identity primary key,
  goal       text,
  start_date date not null,
  end_date   date not null,
  status     text not null default 'planned',
  created_at timestamptz not null default now(),

  constraint sprints_status_check
    check (status = any (array['planned', 'active', 'completed']))
);


-- -----------------------------------------------------------------------------
-- Table profiles : un profil par compte Supabase Auth.
-- Son id est le même que celui de auth.users : supprimer le compte
-- supprime aussi le profil (on delete cascade).
-- L'email est unique ; le rôle vaut « user » ou « admin ».
-- -----------------------------------------------------------------------------
create table public.profiles (
  id         uuid primary key,
  firstname  text,
  lastname   text,
  email      text not null,
  avatar_url text,
  role       text not null default 'user',
  created_at timestamptz not null default now(),

  constraint profiles_email_key unique (email),
  constraint profiles_role_check
    check (role = any (array['user', 'admin'])),
  constraint profiles_id_fkey
    foreign key (id) references auth.users (id) on delete cascade
);


-- -----------------------------------------------------------------------------
-- Table features : les idées, bugs et améliorations.
-- - status, priority, effort et impact n'acceptent que certaines valeurs (CHECK).
--   effort peut rester vide (null) : la contrainte CHECK laisse passer null.
-- - module_id : module obligatoire.
-- - assigned_to : personne assignée ; si son profil est supprimé, la feature
--   devient « non assignée » (on delete set null).
-- - sprint_id : sprint facultatif (null = backlog). Dans la base d'origine,
--   cette colonne n'a PAS de clé étrangère vers sprints : on garde la même chose.
-- -----------------------------------------------------------------------------
create table public.features (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  title       text not null,
  description text,
  status      text not null default 'backlog',
  priority    text not null default 'medium',
  effort      text,
  impact      text not null default 'medium',
  module_id   bigint not null,
  sprint_id   bigint,
  assigned_to uuid,

  constraint features_status_check
    check (status = any (array['backlog', 'todo', 'in_progress', 'done', 'cancelled'])),
  constraint features_priority_check
    check (priority = any (array['critical', 'high', 'medium', 'low', 'nice_to_have'])),
  constraint features_effort_check
    check (effort = any (array['xs', 's', 'm', 'l', 'xl'])),
  constraint features_impact_check
    check (impact = any (array['low', 'medium', 'high'])),

  constraint features_module_id_fkey
    foreign key (module_id) references public.modules (id)
    on update cascade,
  constraint features_assigned_to_fkey
    foreign key (assigned_to) references public.profiles (id)
    on update cascade on delete set null
);


-- -----------------------------------------------------------------------------
-- Table comments : les commentaires d'une feature, avec leur auteur.
-- Pas de suppression en cascade : une feature qui a des commentaires ne peut
-- pas être supprimée tant qu'on n'a pas supprimé ses commentaires.
-- -----------------------------------------------------------------------------
create table public.comments (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  content    text not null,
  feature_id bigint not null,
  author_id  uuid not null,

  constraint comments_feature_id_fkey
    foreign key (feature_id) references public.features (id)
    on update cascade,
  constraint comments_author_id_fkey
    foreign key (author_id) references public.profiles (id)
    on update cascade
);


-- -----------------------------------------------------------------------------
-- Sécurité (RLS) : dans la base d'origine, la Row Level Security est
-- DÉSACTIVÉE sur les 5 tables et aucune policy n'existe.
-- On reproduit cet état à l'identique (rien à écrire : une nouvelle table
-- n'a pas de RLS par défaut).
-- À corriger dans une prochaine migration avant une vraie mise en production.
-- -----------------------------------------------------------------------------


-- -----------------------------------------------------------------------------
-- Fonction handle_new_user : crée le profil d'une personne qui vient de
-- s'inscrire, avec son id et son email (le prénom et le nom sont complétés
-- ensuite par l'app).
-- - security definer : elle s'exécute avec les droits de son propriétaire,
--   car la personne qui s'inscrit n'a pas encore le droit d'écrire dans profiles.
-- - search_path vide : la fonction n'utilise que des noms complets
--   (public.profiles), ce qui évite qu'un autre schéma la détourne.
-- -----------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$;


-- -----------------------------------------------------------------------------
-- Trigger on_auth_user_created : après chaque nouveau compte dans auth.users,
-- appelle handle_new_user() pour créer le profil correspondant.
-- -----------------------------------------------------------------------------
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- -----------------------------------------------------------------------------
-- Storage : bucket « avatars » pour les photos de profil (hors schéma public).
-- public = true : chaque photo a une adresse lisible sans être connecté.
-- C'est une ligne de configuration dont l'app a besoin, pas une donnée métier.
-- -----------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true);


-- -----------------------------------------------------------------------------
-- Storage : une personne connectée peut déposer une photo, mais seulement
-- dans son propre dossier (avatars/<son id>/…). La lecture n'a pas besoin
-- de policy, car le bucket est public.
-- -----------------------------------------------------------------------------
create policy "Avatar : dépôt dans son dossier"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'avatars'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);
